def pytest_collection_modifyitems(
    config: pytest.Config, items: list[pytest.Item]
) -> None:
    """Mark each pending ``test_case`` item as a strict xfail on ``Pending``."""
    config.stash[PENDING_KEY] = PENDING_IDS
    unknown = PENDING_IDS - {case.id for case in ALL_CASES}
    if unknown:
        msg = f"PENDING_IDS names no case: {sorted(unknown)}"
        raise pytest.UsageError(msg)
    for item in items:
        if not isinstance(item, pytest.Function) or item.originalname != "test_case":
            continue
        callspec = getattr(item, "callspec", None)
        if callspec is not None and callspec.id in PENDING_IDS:
            item.add_marker(
                pytest.mark.xfail(raises=Pending, strict=True, reason="AL2b")
            )
